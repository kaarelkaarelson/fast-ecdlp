#!/usr/bin/env python3
"""L173: data for ECDLP/L173_E0Quarter.lean: the two e0 = 1/4 + 1/(2K0) schedules of L161 (free zeta x0=8; paper x0=18),
Fraction arithmetic, outward rounding to 12 digits, same conventions as gen_L149.py."""
from fractions import Fraction as F
from math import isqrt
D=10**12; LN2=F(6931471808,10**10); RHO=F(707106781187,D)
def cdiv(a,b): return -(-a//b)
def run(x0, ss, zs=None):
    x=x0; E=F(1,4)+F(1,2*2**x0); E0=E; rows=[]
    for l,s in enumerate(ss):
        if zs is None:
            q=LN2*(1+2*x+s)/F(2**(s+1)); n=cdiv(q.numerator*D*D,q.denominator); zn=isqrt(n)
            if zn*zn<n: zn+=1
            z=F(zn,D); zl=f"({zn}:ℚ)/1000000000000"
        else:
            z=zs[l]; zl=f"(1:ℚ)/{z.denominator}"
        assert z*z*2**(s+1)>=LN2*(1+2*x+s) and z<=1
        t=min(x,60); R=(RHO+3*z)*E+F(3,2**t)
        En=F(cdiv(R.numerator*D,R.denominator),D); assert En<=1
        rows.append(f"  ({s}, {zl}, ({En.numerator*(D//En.denominator)}:ℚ)/1000000000000)"); E=En; x=2*(x+s)
    return rows,x,E,E0
c1=F(890104,10**4)
FREE=[13,17,21,25,27,31,34,37,40,44,47,49,51,66,66,79,79,79]
PAPER=[3*l+18 for l in range(18)]; PZ=[F(1,2**(l+5)) for l in range(18)]
out=["-- AUTO-GENERATED by gen_L173.py"]
for name,x0,ss,zs in (("schedQFree",8,FREE,None),("schedQPaper",18,PAPER,PZ)):
    rows,x,E,E0=run(x0,ss,zs)
    out.append(f"-- {name}: x0={x0} E0={E0} x_n={x} E_n={float(E):.9e} E_n*c1*5={float(E*c1*5):.6f}")
    out.append(f"def {name} : List (ℕ × ℚ × ℚ) := [\n"+",\n".join(rows)+"]\n")
    assert E*c1*5<=F(2999,10**4), (name, float(E*c1*5))
print("\n".join(out))
